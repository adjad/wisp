#!/usr/bin/env python3
"""Build v3_replay.{train,dev}.jsonl: a fixed, category-stratified sample of WHOLE V3 conversations (every row of each
picked conversation), so continued training from the V3 weights on the V3.1 fixes keeps V3's behaviour.

The V3 rows are regenerated byte-identically by ../ling-dataset-v3-20261012/generate.py (checked against V3_TRAIN_SHA256),
then sampled with a fixed seed. Row ids get a "v3r-" prefix; everything else is byte-for-byte the V3 row.

    python3 v3_replay.py            # writes v3_replay.train.jsonl, v3_replay.dev.jsonl, v3_replay.provenance.jsonl
"""
import hashlib, json, random, subprocess, sys, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
V3_DIR = HERE.parent / "ling-dataset-v3-20261012"
V3_TRAIN_SHA256 = "7f61099093d8ec53ebd4acfc7c87a8c18170c00bdb3ac14b2991ffda9ace3702"
SEED = 20261013
TARGET_ROWS = {"train": 600, "dev": 60}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        subprocess.run([sys.executable, str(V3_DIR / "generate.py"), "--output-dir", str(td)], check=True,
                       stdout=subprocess.DEVNULL)
        if sha(td / "train.jsonl") != V3_TRAIN_SHA256:
            sys.exit("V3 regeneration does not match the V3 release train.jsonl")
        prov_out = []
        for split in ("train", "dev"):
            prov = [json.loads(x) for x in (td / f"{split}.provenance.jsonl").read_text().splitlines() if x]
            lines = [x for x in (td / f"{split}.jsonl").read_text().splitlines() if x]
            by_conv = {}
            for line in lines:
                row = json.loads(line)
                if row["id"].startswith("v2r-"):
                    continue                      # V2 replay is appended separately, in full
                by_conv.setdefault(row["conversation_id"], []).append(line)
            total = sum(len(v) for v in by_conv.values())
            # stratify: each category gets its share of TARGET_ROWS, filled with whole conversations in seeded order
            cats = {}
            for p in prov:
                cats.setdefault(p["category"], []).append(p["conversation_id"])
            rng = random.Random(f"{SEED}-{split}")
            picked = []
            for cat in sorted(cats):
                ids = sorted(cats[cat])
                rng.shuffle(ids)
                share = TARGET_ROWS[split] * sum(len(by_conv[i]) for i in ids) / total
                got = 0
                for cid in ids:
                    if got >= share:
                        break
                    picked.append(cid)
                    got += len(by_conv[cid])
            picked_set = set(picked)
            out = []
            for line in lines:
                row = json.loads(line)
                if row.get("conversation_id") in picked_set:
                    out.append(line.replace(f'"id":"{row["id"]}"', f'"id":"v3r-{row["id"]}"', 1))
            assert all('"id":"v3r-' in x for x in out)
            (HERE / f"v3_replay.{split}.jsonl").write_text("".join(x + "\n" for x in out))
            cat_of = {p["conversation_id"]: p["category"] for p in prov}
            for cid in sorted(picked_set):
                prov_out.append({"split": split, "source_conversation_id": cid, "category": cat_of[cid],
                                 "rows": len(by_conv[cid])})
            print(f"{split}: {len(picked_set)} conversations, {len(out)} rows")
        (HERE / "v3_replay.provenance.jsonl").write_text(
            json.dumps({"v3_train_sha256": V3_TRAIN_SHA256, "seed": SEED, "target_rows": TARGET_ROWS,
                        "train_sha256": sha(HERE / "v3_replay.train.jsonl"),
                        "dev_sha256": sha(HERE / "v3_replay.dev.jsonl")}) + "\n"
            + "".join(json.dumps(p) + "\n" for p in prov_out))


if __name__ == "__main__":
    main()
