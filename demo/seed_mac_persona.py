#!/usr/bin/env python3
"""Seed the FICTIONAL Wisp demo persona into this Mac's real apps.

The persona (Aria Solano, founder & CEO of the fictional company Cedarloop) is
generated by ``service.behavior.persona.generate_persona``: about eight weeks of
history plus two weeks ahead (gym mornings, back-to-back meetings that get
cancelled, 1:1s, ...). This script writes it into the user's REAL Calendar,
Reminders and Notes so Wisp's ordinary native readers see a lived-in Mac during
the behavior demo.

Everything goes into dedicated containers named "Wisp Demo" (a calendar, a
Reminders list and a Notes folder in the default account). Every item carries
a ``[wisp-demo-id:<id>]`` marker, which makes seeding idempotent: items whose
marker already exists are skipped. ``remove`` deletes those three containers
and nothing else.

  seed   [--calendar] [--reminders] [--notes] [--all] [--dry-run]
         [--weeks-back 8] [--weeks-ahead 2] [--seed 11] [--tz ZONE]
  remove [--calendar] [--reminders] [--notes] [--dry-run] [--yes]

With no kind flags, all three kinds are used. ``--dry-run`` prints the
generated AppleScript instead of running it (works on any OS). Real runs need
macOS and grant Terminal automation access to Calendar/Reminders/Notes on the
first run.

Runs on the macOS system Python (3.9+); standard library only.
"""
from __future__ import annotations

import argparse
import os
import platform
import re
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTAINER = "Wisp Demo"
MARKER_PREFIX = "wisp-demo-id:"
CHUNK_SIZE = 50
KINDS = ("calendar", "reminders", "notes")
DEFAULT_TZ = "America/Los_Angeles"
FICTION_LINE = "Fictional Wisp demo data (Aria Solano / Cedarloop). Safe to delete."

APP_FOR_KIND = {"calendar": "Calendar", "reminders": "Reminders", "notes": "Notes"}


class OsaError(RuntimeError):
    """osascript failed (permissions, missing container, AppleScript error)."""


# ---------------------------------------------------------------------------
# AppleScript building blocks
# ---------------------------------------------------------------------------

def marker(demo_id: str) -> str:
    """The idempotency marker. Bracketed so ``x-1`` never matches ``x-10``."""
    safe = re.sub(r"[^A-Za-z0-9._:-]", "-", str(demo_id)) or "item"
    return "[" + MARKER_PREFIX + safe + "]"


def as_string(text) -> str:
    """Return an AppleScript expression that evaluates to ``text``.

    Quotes and backslashes are escaped; newlines/tabs become ``linefeed`` /
    ``tab`` constants; non-ASCII runs become ``character id`` / ``string id`` so
    the script itself is pure ASCII and immune to source-encoding guesses.
    Other control characters are dropped.
    """
    text = "" if text is None else str(text)
    parts = []
    buf = []
    ids = []

    def flush_buf():
        if buf:
            parts.append('"' + "".join(buf) + '"')
            del buf[:]

    def flush_ids():
        if ids:
            if len(ids) == 1:
                parts.append("(character id %d)" % ids[0])
            else:
                parts.append("(string id {%s})" % ", ".join(str(i) for i in ids))
            del ids[:]

    for ch in text.replace("\r\n", "\n").replace("\r", "\n"):
        code = ord(ch)
        if ch == "\n" or ch == "\t":
            flush_buf()
            flush_ids()
            parts.append("linefeed" if ch == "\n" else "tab")
        elif code > 126:
            flush_buf()
            ids.append(code)
        elif code < 32 or code == 127:
            continue
        else:
            flush_ids()
            if ch == "\\":
                buf.append("\\\\")
            elif ch == '"':
                buf.append('\\"')
            else:
                buf.append(ch)
    flush_buf()
    flush_ids()
    if not parts:
        return '""'
    if len(parts) == 1:
        return parts[0]
    return "(" + " & ".join(parts) + ")"


DATE_HANDLER = """on wispDate(y, m, d, s)
\t-- Build dates field by field: never parse locale-dependent date strings.
\tset dt to current date
\tset day of dt to 1
\tset year of dt to y
\tset month of dt to m
\tset day of dt to d
\tset time of dt to s
\treturn dt
end wispDate
"""


def as_date(ts: float) -> str:
    """AppleScript expression for epoch ``ts`` in the Mac's local time."""
    d = datetime.fromtimestamp(float(ts))
    secs = d.hour * 3600 + d.minute * 60 + d.second
    return "my wispDate(%d, %d, %d, %d)" % (d.year, d.month, d.day, secs)


def html_escape(text: str) -> str:
    return (str(text).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


def chunked(items: list, size: int = CHUNK_SIZE) -> list:
    size = max(1, int(size))
    return [items[i:i + size] for i in range(0, len(items), size)]


def _existing_text_block(list_expr: str) -> str:
    return (
        "\tset existingText to \"\"\n"
        "\tset existingValues to " + list_expr + "\n"
        "\trepeat with v in existingValues\n"
        "\t\ttry\n"
        "\t\t\tset existingText to existingText & ((contents of v) as text) & linefeed\n"
        "\t\tend try\n"
        "\tend repeat\n"
    )


_TALLY_START = "set createdCount to 0\nset skippedCount to 0\n"
_TALLY_END = 'return "created " & createdCount & " skipped " & skippedCount\n'


def _guard(item_marker: str, body: str) -> str:
    return ("\tif existingText does not contain " + as_string(item_marker) + " then\n"
            + body
            + "\t\tset createdCount to createdCount + 1\n"
            "\telse\n"
            "\t\tset skippedCount to skippedCount + 1\n"
            "\tend if\n")


# ---------------------------------------------------------------------------
# Item normalization (persona rows may be dicts or simple objects)
# ---------------------------------------------------------------------------

def _get(item, key, default=None):
    if isinstance(item, dict):
        return item.get(key, default)
    return getattr(item, key, default)


def _number(value):
    try:
        out = float(value)
    except (TypeError, ValueError):
        return None
    return out if out == out and out not in (float("inf"), float("-inf")) else None


def normalize_events(rows) -> list:
    out = []
    for row in rows or ():
        start = _number(_get(row, "start_ts"))
        demo_id = _get(row, "demo_id")
        title = _get(row, "title")
        if start is None or not demo_id or not title:
            continue
        end = _number(_get(row, "end_ts"))
        if end is None or end <= start:
            end = start + 1800
        out.append({"demo_id": str(demo_id), "title": str(title), "start_ts": start,
                    "end_ts": end, "location": str(_get(row, "location") or ""),
                    "notes": str(_get(row, "notes") or "")})
    out.sort(key=lambda r: (r["start_ts"], r["demo_id"]))
    return out


def normalize_reminders(rows) -> list:
    out = []
    for row in rows or ():
        demo_id = _get(row, "demo_id")
        title = _get(row, "title")
        if not demo_id or not title:
            continue
        out.append({"demo_id": str(demo_id), "title": str(title),
                    "due_ts": _number(_get(row, "due_ts")),
                    "completed": bool(_get(row, "completed", False)),
                    "notes": str(_get(row, "notes") or "")})
    out.sort(key=lambda r: (r["due_ts"] or 0, r["demo_id"]))
    return out


def normalize_notes(rows) -> list:
    out = []
    for row in rows or ():
        demo_id = _get(row, "demo_id")
        title = _get(row, "title")
        if not demo_id or not title:
            continue
        out.append({"demo_id": str(demo_id), "title": str(title),
                    "body": str(_get(row, "body") or "")})
    return out


def _description(notes: str, demo_id: str) -> str:
    text = notes.strip()
    tail = FICTION_LINE + "\n" + marker(demo_id)
    return (text + "\n\n" + tail) if text else tail


# ---------------------------------------------------------------------------
# Script generators: one script per chunk
# ---------------------------------------------------------------------------

def calendar_script(events: list, container: str = CONTAINER) -> str:
    """Create ``events`` (normalized) in the ``container`` calendar, skipping
    any whose marker already exists in the chunk's date range."""
    name = as_string(container)
    lo = min(e["start_ts"] for e in events) - 86400
    hi = max(e["start_ts"] for e in events) + 86400
    s = DATE_HANDLER + "\n" + _TALLY_START
    s += 'tell application "Calendar"\n'
    s += "\tif not (exists calendar " + name + ") then\n"
    s += "\t\ttry\n"
    s += "\t\t\tmake new calendar with properties {name:" + name + "}\n"
    s += "\t\ton error errMsg\n"
    s += ('\t\t\terror "Could not create the calendar ' + container.replace('"', "'")
          + '. Create it in Calendar.app (File > New Calendar), then rerun. " & errMsg\n')
    s += "\t\tend try\n"
    s += "\tend if\n"
    s += "\tset wispCal to first calendar whose name is " + name + "\n"
    s += "\tset rangeStart to " + as_date(lo) + "\n"
    s += "\tset rangeEnd to " + as_date(hi) + "\n"
    s += _existing_text_block(
        "description of (every event of wispCal whose start date >= rangeStart and start date <= rangeEnd)")
    for e in events:
        body = ("\t\tset sd to " + as_date(e["start_ts"]) + "\n"
                "\t\tset ed to " + as_date(e["end_ts"]) + "\n"
                "\t\ttell wispCal to make new event with properties {summary:" + as_string(e["title"])
                + ", start date:sd, end date:ed, location:" + as_string(e["location"])
                + ", description:" + as_string(_description(e["notes"], e["demo_id"])) + "}\n")
        s += _guard(marker(e["demo_id"]), body)
    s += "end tell\n" + _TALLY_END
    return s


def reminders_script(reminders: list, container: str = CONTAINER) -> str:
    name = as_string(container)
    s = DATE_HANDLER + "\n" + _TALLY_START
    s += 'tell application "Reminders"\n'
    s += "\tif not (exists list " + name + ") then\n"
    s += "\t\tmake new list with properties {name:" + name + "}\n"
    s += "\tend if\n"
    s += "\tset wispList to list " + name + "\n"
    s += _existing_text_block("body of every reminder of wispList")
    for r in reminders:
        props = "{name:" + as_string(r["title"]) + ", body:" + as_string(_description(r["notes"], r["demo_id"]))
        body = ""
        if r["due_ts"] is not None:
            body += "\t\tset dd to " + as_date(r["due_ts"]) + "\n"
            props += ", due date:dd"
        props += "}"
        body += "\t\ttell wispList to set newItem to make new reminder with properties " + props + "\n"
        if r["completed"]:
            body += "\t\tset completed of newItem to true\n"
        s += _guard(marker(r["demo_id"]), body)
    s += "end tell\n" + _TALLY_END
    return s


def note_html(title: str, body: str, demo_id: str) -> str:
    lines = ["<div><h1>" + html_escape(title) + "</h1></div>"]
    for line in str(body).replace("\r\n", "\n").split("\n"):
        lines.append("<div>" + (html_escape(line) if line.strip() else "<br>") + "</div>")
    lines.append("<div><br></div>")
    lines.append("<div>" + html_escape(FICTION_LINE) + "</div>")
    lines.append("<div>" + html_escape(marker(demo_id)) + "</div>")
    return "".join(lines)


def notes_script(notes: list, container: str = CONTAINER) -> str:
    name = as_string(container)
    s = _TALLY_START
    s += 'tell application "Notes"\n'
    s += "\tset wispAccount to default account\n"
    s += "\tif not (exists folder " + name + " of wispAccount) then\n"
    s += "\t\tmake new folder at wispAccount with properties {name:" + name + "}\n"
    s += "\tend if\n"
    s += "\tset wispFolder to folder " + name + " of wispAccount\n"
    s += _existing_text_block("body of every note of wispFolder")
    for n in notes:
        body = ("\t\tmake new note at wispFolder with properties {name:" + as_string(n["title"])
                + ", body:" + as_string(note_html(n["title"], n["body"], n["demo_id"])) + "}\n")
        s += _guard(marker(n["demo_id"]), body)
    s += "end tell\n" + _TALLY_END
    return s


SCRIPT_FOR_KIND = {"calendar": calendar_script, "reminders": reminders_script, "notes": notes_script}


def build_seed_scripts(persona, kinds, chunk_size: int = CHUNK_SIZE, container: str = CONTAINER) -> list:
    """[(kind, item_count, script)] in run order."""
    rows = {
        "calendar": normalize_events(_get(persona, "calendar_events", ())),
        "reminders": normalize_reminders(_get(persona, "reminders", ())),
        "notes": normalize_notes(_get(persona, "notes", ())),
    }
    out = []
    for kind in KINDS:
        if kind not in kinds:
            continue
        for chunk in chunked(rows[kind], chunk_size):
            out.append((kind, len(chunk), SCRIPT_FOR_KIND[kind](chunk, container)))
    return out


def count_script(kinds, container: str = CONTAINER) -> str:
    """Counts what ``remove`` would delete. Read-only."""
    name = as_string(container)
    s = 'set report to ""\n'
    if "calendar" in kinds:
        s += ('tell application "Calendar"\n'
              "\tset n to 0\n"
              "\trepeat with c in (every calendar whose name is " + name + ")\n"
              "\t\tset n to n + (count of events of c)\n"
              "\tend repeat\n"
              '\tset report to report & "calendar " & (count of (every calendar whose name is '
              + name + ')) & " " & n & linefeed\n'
              "end tell\n")
    if "reminders" in kinds:
        s += ('tell application "Reminders"\n'
              "\tset n to 0\n"
              "\tset k to 0\n"
              "\trepeat with l in (every list whose name is " + name + ")\n"
              "\t\tset k to k + 1\n"
              "\t\tset n to n + (count of reminders of l)\n"
              "\tend repeat\n"
              '\tset report to report & "reminders " & k & " " & n & linefeed\n'
              "end tell\n")
    if "notes" in kinds:
        s += ('tell application "Notes"\n'
              "\tset n to 0\n"
              "\tset k to 0\n"
              "\trepeat with a in accounts\n"
              "\t\tif exists folder " + name + " of a then\n"
              "\t\t\tset k to k + 1\n"
              "\t\t\tset n to n + (count of notes of folder " + name + " of a)\n"
              "\t\tend if\n"
              "\tend repeat\n"
              '\tset report to report & "notes " & k & " " & n & linefeed\n'
              "end tell\n")
    return s + "return report\n"


def remove_script(kinds, container: str = CONTAINER) -> str:
    """Deletes ONLY containers named ``container``: the calendar(s), the
    Reminders list(s) and the Notes folder(s) in every account."""
    name = as_string(container)
    s = 'set report to ""\n'
    if "calendar" in kinds:
        s += ('tell application "Calendar"\n'
              "\tset removed to 0\n"
              "\trepeat 10 times\n"
              "\t\tif not (exists calendar " + name + ") then exit repeat\n"
              "\t\ttry\n"
              "\t\t\tdelete (first calendar whose name is " + name + ")\n"
              "\t\t\tset removed to removed + 1\n"
              "\t\ton error errMsg\n"
              '\t\t\tset report to report & "calendar error: " & errMsg & linefeed\n'
              "\t\t\texit repeat\n"
              "\t\tend try\n"
              "\tend repeat\n"
              '\tset report to report & "calendar removed " & removed & linefeed\n'
              "end tell\n")
    if "reminders" in kinds:
        s += ('tell application "Reminders"\n'
              "\tset removed to 0\n"
              "\trepeat 10 times\n"
              "\t\tif not (exists list " + name + ") then exit repeat\n"
              "\t\ttry\n"
              "\t\t\tdelete (first list whose name is " + name + ")\n"
              "\t\t\tset removed to removed + 1\n"
              "\t\ton error errMsg\n"
              '\t\t\tset report to report & "reminders error: " & errMsg & linefeed\n'
              "\t\t\texit repeat\n"
              "\t\tend try\n"
              "\tend repeat\n"
              '\tset report to report & "reminders removed " & removed & linefeed\n'
              "end tell\n")
    if "notes" in kinds:
        s += ('tell application "Notes"\n'
              "\tset removed to 0\n"
              "\trepeat with a in accounts\n"
              "\t\trepeat 10 times\n"
              "\t\t\tif not (exists folder " + name + " of a) then exit repeat\n"
              "\t\t\ttry\n"
              "\t\t\t\tdelete folder " + name + " of a\n"
              "\t\t\t\tset removed to removed + 1\n"
              "\t\t\ton error errMsg\n"
              '\t\t\t\tset report to report & "notes error: " & errMsg & linefeed\n'
              "\t\t\t\texit repeat\n"
              "\t\t\tend try\n"
              "\t\tend repeat\n"
              "\tend repeat\n"
              '\tset report to report & "notes removed " & removed & linefeed\n'
              "end tell\n")
    return s + "return report\n"


# ---------------------------------------------------------------------------
# Running
# ---------------------------------------------------------------------------

def is_macos() -> bool:
    return platform.system() == "Darwin"


def run_osascript(script: str, timeout: float = 900) -> str:
    try:
        proc = subprocess.run(["osascript", "-"], input=script, capture_output=True,
                              text=True, timeout=timeout)
    except FileNotFoundError:
        raise OsaError("osascript not found (macOS only)")
    except subprocess.TimeoutExpired:
        raise OsaError("osascript timed out after %ds" % timeout)
    if proc.returncode != 0:
        err = (proc.stderr or "").strip() or "osascript exited with %d" % proc.returncode
        if "-1743" in err or "Not authorized" in err:
            err += ("\nAllow Terminal (or your shell app) under System Settings > Privacy & Security"
                    " > Automation, then rerun.")
        raise OsaError(err)
    return (proc.stdout or "").strip()


def parse_tally(output: str):
    m = re.search(r"created (\d+) skipped (\d+)", output or "")
    return (int(m.group(1)), int(m.group(2))) if m else (0, 0)


def local_tz_name() -> str:
    """IANA name of this machine's zone (macOS: /etc/localtime symlink)."""
    env = os.environ.get("TZ", "")
    if "/" in env:
        return env.lstrip(":")
    try:
        target = os.path.realpath("/etc/localtime")
    except OSError:
        return DEFAULT_TZ
    marker_dir = "zoneinfo/"
    if marker_dir in target:
        return target.split(marker_dir, 1)[1]
    return DEFAULT_TZ


def load_persona(now: float, tz: str, weeks_back: int, weeks_ahead: int, seed: int):
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    try:
        from service.behavior.persona import generate_persona  # noqa: E402
    except ImportError as exc:
        raise SystemExit("cannot load the persona generator (service.behavior.persona): %s. "
                         "Run from a checkout that includes the behavior engine." % exc)
    return generate_persona(now, tz=tz, weeks_back=weeks_back, weeks_ahead=weeks_ahead, seed=seed)


def _kinds(args) -> tuple:
    chosen = tuple(k for k in KINDS if getattr(args, k, False))
    if getattr(args, "all", False) or not chosen:
        return KINDS
    return chosen


def cmd_seed(args, out=None) -> int:
    out = out or sys.stdout
    kinds = _kinds(args)
    if not args.dry_run and not is_macos():
        out.write("seed writes to macOS Calendar/Reminders/Notes and only runs on macOS. "
                  "Use --dry-run to print the AppleScript.\n")
        return 2
    persona = load_persona(time.time(), args.tz, args.weeks_back, args.weeks_ahead, args.seed)
    scripts = build_seed_scripts(persona, kinds, args.chunk)
    totals = {k: [0, 0, 0] for k in kinds}   # items, created, skipped
    out.write("Seeding FICTIONAL persona (Aria Solano, Cedarloop) into %r containers: %s\n"
              % (CONTAINER, ", ".join(kinds)))
    for i, (kind, count, script) in enumerate(scripts, 1):
        totals[kind][0] += count
        if args.dry_run:
            out.write("-- chunk %d/%d: %s, %d item(s)\n%s\n" % (i, len(scripts), kind, count, script))
            continue
        try:
            created, skipped = parse_tally(run_osascript(script))
        except OsaError as exc:
            out.write("%s chunk %d failed: %s\n" % (APP_FOR_KIND[kind], i, exc))
            return 1
        totals[kind][1] += created
        totals[kind][2] += skipped
    for kind in kinds:
        items, created, skipped = totals[kind]
        if args.dry_run:
            out.write("%-9s %d item(s) in %r (dry run, nothing written)\n" % (kind, items, CONTAINER))
        else:
            out.write("%-9s %d item(s): %d created, %d already present\n" % (kind, items, created, skipped))
    if not args.dry_run:
        out.write("Remove everything later with: python3 demo/seed_mac_persona.py remove\n")
    return 0


def _confirm(prompt: str) -> bool:
    try:
        return input(prompt).strip().lower() in ("y", "yes")
    except EOFError:
        return False


def cmd_remove(args, out=None) -> int:
    out = out or sys.stdout
    kinds = _kinds(args)
    script = remove_script(kinds)
    if args.dry_run:
        out.write("-- would count with:\n%s\n-- would remove with:\n%s\n" % (count_script(kinds), script))
        return 0
    if not is_macos():
        out.write("remove only runs on macOS. Use --dry-run to print the AppleScript.\n")
        return 2
    try:
        counts = run_osascript(count_script(kinds))
    except OsaError as exc:
        out.write("Could not inspect the %r containers: %s\n" % (CONTAINER, exc))
        return 1
    out.write("Found (kind, containers named %r, items inside):\n%s\n" % (CONTAINER, counts))
    if not args.yes and not _confirm("Delete ONLY these %r containers and their items? [y/N] " % CONTAINER):
        out.write("Nothing removed.\n")
        return 1
    try:
        out.write(run_osascript(script) + "\n")
    except OsaError as exc:
        out.write("Remove failed: %s\n" % exc)
        return 1
    out.write("Notes moves deleted notes to Recently Deleted; empty it there if you want them gone now.\n")
    return 0


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd")
    sub.required = True
    seed = sub.add_parser("seed", help="add the fictional persona to Calendar/Reminders/Notes")
    remove = sub.add_parser("remove", help="delete the 'Wisp Demo' containers")
    for p in (seed, remove):
        for kind in KINDS:
            p.add_argument("--" + kind, action="store_true")
        p.add_argument("--all", action="store_true")
        p.add_argument("--dry-run", action="store_true", help="print the AppleScript, change nothing")
    seed.add_argument("--weeks-back", type=int, default=8)
    seed.add_argument("--weeks-ahead", type=int, default=2)
    seed.add_argument("--seed", type=int, default=11)
    seed.add_argument("--tz", default=local_tz_name(), help="persona time zone (default: this Mac's)")
    seed.add_argument("--chunk", type=int, default=CHUNK_SIZE, help="items per osascript call")
    seed.set_defaults(fn=cmd_seed)
    remove.add_argument("--yes", action="store_true", help="skip the confirmation prompt")
    remove.set_defaults(fn=cmd_remove)
    return ap


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
